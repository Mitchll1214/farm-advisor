/**
 * 按 id 或别名匹配作物，未匹配到则回落到通用档案。
 * 注意：前端 public/index.html 的作物下拉框与本表的 id 一一对应，新增作物时需同步。
 */
export function resolveCrop(requested: string | null | undefined): CropProfile {
  if (typeof requested !== "string") return GENERAL;
  const key = requested.trim().toLowerCase();
  if (!key) return GENERAL;
  const matched = CROPS.find(
    (crop) => crop.id === key || crop.aliases.some((alias) => alias.toLowerCase() === key),
  );
  return matched ?? GENERAL;
}
